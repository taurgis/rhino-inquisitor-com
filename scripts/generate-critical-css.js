#!/usr/bin/env node
/**
 * Regenerate the per-page-type critical (above-the-fold) CSS from the built site.
 *
 * Why: the inlined `src/assets/styles/critical-{home,archive,post}.css` files are
 * the above-the-fold subset of the full stylesheet. After the "Paper & Ink"
 * redesign they drifted out of sync with `site.css`, so the async stylesheet swap
 * reflowed above-the-fold content (Cumulative Layout Shift on archive/post pages).
 *
 * This script re-extracts them with penthouse from a representative rendered page
 * of each type, at both mobile and desktop widths, so first paint matches the final
 * layout and the async inline-critical path stays CLS-free.
 *
 * Prerequisites: run a production build first (`npm run build:prod`) so
 * `public/` and the fingerprinted `public/styles/site.min.*.css` exist.
 *
 * Usage: node scripts/generate-critical-css.js
 *
 * penthouse strips @font-face, so the layout partial keeps prepending the
 * self-hosted @font-face fragment (`styles/fragments/fonts.css`) to the inline
 * critical block — see layouts/partials/site/stylesheet.html.
 */
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import penthouse from 'penthouse';
import puppeteer from 'puppeteer';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(repoRoot, 'public');
const outDir = path.join(repoRoot, 'src', 'assets', 'styles');
const PORT = 8799;

// Representative page per type. The post uses a content-heavy article so its
// above-the-fold hero/meta layout is captured.
const TARGETS = [
  { name: 'critical-home', route: '/' },
  { name: 'critical-archive', route: '/category/ai/' },
  { name: 'critical-post', route: '/the-attribute-fallback-system-in-sfcc/' },
];

// Extract at both the mobile emulation width the perf gate uses and a desktop
// width, then union the rules so first paint is correct at every breakpoint.
const DIMENSIONS = [
  { width: 390, height: 900 },
  { width: 1280, height: 900 },
];

const MIME = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.avif': 'image/avif', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.xml': 'application/xml', '.ico': 'image/x-icon' };

function startServer() {
  const server = http.createServer((req, res) => {
    let urlPath = decodeURIComponent(req.url.split('?')[0]);
    let filePath = path.join(publicDir, urlPath);
    if (filePath.endsWith('/')) filePath = path.join(filePath, 'index.html');
    if (!filePath.startsWith(publicDir)) { res.writeHead(403); res.end(); return; }
    fs.readFile(filePath, (err, data) => {
      if (err) { res.writeHead(404); res.end('not found'); return; }
      res.writeHead(200, { 'content-type': MIME[path.extname(filePath)] || 'application/octet-stream' });
      res.end(data);
    });
  });
  return new Promise((resolve) => server.listen(PORT, () => resolve(server)));
}

function findFullCss() {
  const dir = path.join(publicDir, 'styles');
  const match = fs.readdirSync(dir).find((f) => /^site\.min\..*\.css$/.test(f));
  if (!match) throw new Error('Built stylesheet public/styles/site.min.*.css not found — run `npm run build:prod` first.');
  return path.join(dir, match);
}

async function main() {
  const fullCssPath = findFullCss();
  const cssString = fs.readFileSync(fullCssPath, 'utf8');
  console.log(`Full stylesheet: ${path.relative(repoRoot, fullCssPath)} (${cssString.length} bytes)`);

  const server = await startServer();
  const getBrowser = async () => puppeteer.launch({ args: ['--no-sandbox', '--disable-dev-shm-usage'] });

  try {
    for (const target of TARGETS) {
      const url = `http://localhost:${PORT}${target.route}`;
      const parts = [];
      for (const dim of DIMENSIONS) {
        const critical = await penthouse({
          url,
          cssString,
          width: dim.width,
          height: dim.height,
          timeout: 90000,
          puppeteer: { getBrowser },
        });
        parts.push(`/* ${target.route} @${dim.width}px */\n${critical.trim()}\n`);
        console.log(`  ${target.name} @${dim.width}px -> ${critical.length} bytes`);
      }
      const header = `/* GENERATED by scripts/generate-critical-css.js — do not edit by hand.\n   Above-the-fold critical CSS extracted from site.css for ${target.route}.\n   Regenerate after redesign/layout changes: build, then npm run generate:critical-css. */\n`;
      const outPath = path.join(outDir, `${target.name}.css`);
      fs.writeFileSync(outPath, header + parts.join('\n'), 'utf8');
      console.log(`  wrote ${path.relative(repoRoot, outPath)}`);
    }
  } finally {
    server.close();
  }
  console.log('Done. Rebuild to inline the regenerated critical CSS.');
}

main().catch((error) => { console.error(error); process.exit(1); });
